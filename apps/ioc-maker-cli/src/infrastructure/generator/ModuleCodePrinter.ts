import { ClassInfo, FactoryInfo, ValueInfo } from '../../domain/types';
import { TokenSets } from './RegistrationPlanner';
import { ImportCollector } from './ImportCollector';
import { ContainerCodePrinter } from './ContainerCodePrinter';

export interface ModuleFile {
  path: string;
  content: string;
}

export interface ModularOutput {
  mainFile: { path: string; content: string };
  moduleFiles: ModuleFile[];
}

/**
 * Produces modular container output: a main container.gen.ts that registers
 * modules, and one *.module.ts file per module.
 */
export class ModuleCodePrinter {
  static print(
    outputPath: string,
    moduleGroupedClasses: Map<string, ClassInfo[]>,
    tokens: TokenSets,
    allProjectClasses: ClassInfo[],
    moduleGroupedFactories?: Map<string, FactoryInfo[]>,
    moduleGroupedValues?: Map<string, ValueInfo[]>
  ): ModularOutput {
    const outputDir = outputPath.substring(0, outputPath.lastIndexOf('/'));
    const modulesDir = `${outputDir}/modules`;

    const allModuleNames = new Set<string>(
      [
        ...moduleGroupedClasses.keys(),
        ...(moduleGroupedFactories?.keys() ?? []),
        ...(moduleGroupedValues?.keys() ?? []),
      ].sort()
    );

    const moduleFiles: ModuleFile[] = [];
    const moduleImports: string[] = [];

    for (const moduleName of allModuleNames) {
      const classes = moduleGroupedClasses.get(moduleName) ?? [];
      const factories = moduleGroupedFactories?.get(moduleName);
      const values = moduleGroupedValues?.get(moduleName);

      const moduleVarName =
        moduleName.charAt(0).toLowerCase() + moduleName.slice(1);
      const moduleFilename = `${moduleVarName}.module.ts`;
      const moduleFilePath = `${modulesDir}/${moduleFilename}`;

      const content = this.printModuleFile(
        moduleName,
        classes,
        moduleFilePath,
        tokens,
        allProjectClasses,
        factories,
        values
      );

      moduleFiles.push({ path: moduleFilePath, content });
      moduleImports.push(
        `import { ${moduleVarName} } from './modules/${moduleVarName}.module';`
      );
    }

    const baseFilename =
      outputPath.split('/').pop()?.replace(/\.ts$/, '') ?? 'container.gen';
    const dtsFilename = baseFilename.replace(/\.gen$/, '.gen.d');

    const moduleInstantiations = Array.from(allModuleNames)
      .map((name) => {
        const varName = name.charAt(0).toLowerCase() + name.slice(1);
        return `container.registerModule(${varName});`;
      })
      .join('\n');

    const mainContent = `/**
 * This file is auto-generated by ioc-arise.
 * Do not modify this file manually.
 */
import { Container } from '@notjustcoders/di-container';
import type { ContainerRegistry } from './${dtsFilename}';
${moduleImports.join('\n')}

export const container = new Container<ContainerRegistry>();

${moduleInstantiations}
`;

    return {
      mainFile: { path: outputPath, content: mainContent },
      moduleFiles,
    };
  }

  private static printModuleFile(
    moduleName: string,
    classes: ClassInfo[],
    moduleFilePath: string,
    tokens: TokenSets,
    allProjectClasses: ClassInfo[],
    factories?: FactoryInfo[],
    values?: ValueInfo[]
  ): string {
    // Build module-specific abstract class names (deps that look abstract)
    const modTokens: TokenSets = {
      interfaceNames: tokens.interfaceNames,
      abstractClassNames: new Set<string>(),
      classNames: tokens.classNames,
    };
    classes.forEach((cls) => {
      cls.dependencies.forEach((dep) => {
        const isInModule = classes.some((c) => c.name === dep.name);
        if (
          !isInModule &&
          (dep.name.startsWith('Abstract') || dep.name.includes('Abstract'))
        ) {
          modTokens.abstractClassNames.add(dep.name);
        }
      });
    });

    const imports = ImportCollector.collect(
      classes,
      moduleFilePath,
      modTokens,
      factories,
      values,
      allProjectClasses
    );

    const classRegs = this.printModuleClassRegistrations(classes, modTokens);
    const factoryRegs =
      factories && factories.length > 0
        ? this.printModuleFactoryRegistrations(factories, modTokens)
        : '';
    const valueRegs =
      values && values.length > 0
        ? this.printModuleValueRegistrations(values)
        : '';

    const allRegs = [classRegs, factoryRegs, valueRegs]
      .filter(Boolean)
      .join('\n');

    const moduleVarName =
      moduleName.charAt(0).toLowerCase() + moduleName.slice(1);

    return `/**
 * This file is auto-generated by ioc-arise.
 * Do not modify this file manually.
 *
 * Module: ${moduleName}
 */
import { ContainerModule, Lifecycle } from '@notjustcoders/di-container';
${imports}

export const ${moduleVarName} = new ContainerModule()
${allRegs};
`;
  }

  private static printModuleClassRegistrations(
    classes: ClassInfo[],
    tokens: TokenSets
  ): string {
    return classes
      .map((cls) => {
        const token = cls.interfaceName
          ? `'${cls.interfaceName}'`
          : cls.abstractClassName
          ? `'${cls.abstractClassName}'`
          : cls.name;

        const deps =
          cls.dependencies.length > 0
            ? `, dependencies: [${cls.dependencies
                .map((d) => ContainerCodePrinter.depToken(d, tokens))
                .join(', ')}]`
            : '';

        const lifecycle =
          cls.scope === 'singleton' ? 'Lifecycle.Singleton' : 'Lifecycle.Transient';

        return `  .register(${token}, { useClass: ${cls.name}${deps}, lifecycle: ${lifecycle} })`;
      })
      .join('\n');
  }

  private static printModuleFactoryRegistrations(
    factories: FactoryInfo[],
    tokens: TokenSets
  ): string {
    return factories
      .map((f) => {
        const token = f.token ? `'${f.token}'` : `'${f.name}'`;

        const deps =
          f.dependencies.length > 0
            ? `, dependencies: [${f.dependencies
                .map((d) => ContainerCodePrinter.depToken(d, tokens))
                .join(', ')}]`
            : '';

        const lifecycle =
          f.scope === 'singleton' ? 'Lifecycle.Singleton' : 'Lifecycle.Transient';
        const factoryExpr = ContainerCodePrinter.factoryExpression(f);

        return `  .register(${token}, { useFactory: ${factoryExpr}${deps}, lifecycle: ${lifecycle} })`;
      })
      .join('\n');
  }

  private static printModuleValueRegistrations(values: ValueInfo[]): string {
    return values
      .map((v) => {
        const token = v.token
          ? `'${v.token}'`
          : v.interfaceName
          ? `'${v.interfaceName}'`
          : `'${v.name}'`;
        return `  .register(${token}, { useValue: ${v.name}, lifecycle: Lifecycle.Singleton })`;
      })
      .join('\n');
  }
}
