import { ClassInfo, DependencyInfo, FactoryInfo, ValueInfo } from '../../domain/types';
import { TokenSets } from './RegistrationPlanner';
import { ImportCollector } from './ImportCollector';

/**
 * Produces the flat (non-modular) container.gen.ts file content.
 */
export class ContainerCodePrinter {
  static print(
    classes: ClassInfo[],
    outputPath: string,
    tokens: TokenSets,
    factories?: FactoryInfo[],
    values?: ValueInfo[]
  ): string {
    const imports = ImportCollector.collect(
      classes,
      outputPath,
      tokens,
      factories,
      values,
      classes
    );

    const dtsFilename = outputPath
      .split('/')
      .pop()
      ?.replace(/\.ts$/, '.d') ?? 'container.gen.d';

    const classRegs = this.printClassRegistrations(classes, tokens);
    const factoryRegs =
      factories && factories.length > 0
        ? this.printFactoryRegistrations(factories, tokens)
        : '';
    const valueRegs =
      values && values.length > 0
        ? this.printValueRegistrations(values)
        : '';

    const allRegs = [classRegs, factoryRegs, valueRegs]
      .filter(Boolean)
      .join('\n\n');

    return `/**
 * This file is auto-generated by ioc-arise.
 * Do not modify this file manually.
 */
import { Container, Lifecycle } from '@notjustcoders/di-container';
import type { ContainerRegistry } from './${dtsFilename}';
${imports}

export const container = new Container<ContainerRegistry>();

${allRegs}
`;
  }

  private static printClassRegistrations(
    classes: ClassInfo[],
    tokens: TokenSets
  ): string {
    return classes
      .map((cls) => {
        const token = cls.interfaceName
          ? `'${cls.interfaceName}'`
          : cls.abstractClassName
          ? `'${cls.abstractClassName}'`
          : cls.name;

        const deps =
          cls.dependencies.length > 0
            ? `\n  dependencies: [${cls.dependencies
                .map((d) => this.depToken(d, tokens))
                .join(', ')}],`
            : '';

        const lifecycle =
          cls.scope === 'singleton' ? 'Lifecycle.Singleton' : 'Lifecycle.Transient';

        return `container.register(${token}, {\n  useClass: ${cls.name},${deps}\n  lifecycle: ${lifecycle},\n});`;
      })
      .join('\n\n');
  }

  static printFactoryRegistrations(
    factories: FactoryInfo[],
    tokens: TokenSets
  ): string {
    return factories
      .map((f) => {
        const token = f.token ? `'${f.token}'` : `'${f.name}'`;

        const deps =
          f.dependencies.length > 0
            ? `\n  dependencies: [${f.dependencies
                .map((d) => this.depToken(d, tokens))
                .join(', ')}],`
            : '';

        const lifecycle =
          f.scope === 'singleton' ? 'Lifecycle.Singleton' : 'Lifecycle.Transient';

        const factoryExpr = this.factoryExpression(f);

        return `container.register(${token}, {\n  useFactory: ${factoryExpr},${deps}\n  lifecycle: ${lifecycle},\n});`;
      })
      .join('\n\n');
  }

  static printValueRegistrations(values: ValueInfo[]): string {
    return values
      .map((v) => {
        const token = v.token
          ? `'${v.token}'`
          : v.interfaceName
          ? `'${v.interfaceName}'`
          : `'${v.name}'`;
        const lifecycle =
          v.scope === 'singleton' ? 'Lifecycle.Singleton' : 'Lifecycle.Transient';
        return `container.register(${token}, {\n  useValue: ${v.name},\n  lifecycle: ${lifecycle},\n});`;
      })
      .join('\n\n');
  }

  static depToken(dep: DependencyInfo, tokens: TokenSets): string {
    if (tokens.interfaceNames.has(dep.name)) return `'${dep.name}'`;
    if (tokens.abstractClassNames.has(dep.name)) return `'${dep.name}'`;
    if (tokens.classNames.has(dep.name)) return dep.name;
    return `'${dep.name}'`;
  }

  static factoryExpression(f: FactoryInfo): string {
    if (f.useContextObject && f.contextObjectProperties) {
      const depParams = f.dependencies
        .map((_, i) => f.contextObjectProperties?.[i]?.name ?? `dep${i}`)
        .join(', ');
      const ctxObject = f.contextObjectProperties.map((p) => p.name).join(', ');
      return `(${depParams}) => ${f.name}({ ${ctxObject} })`;
    }
    return f.name;
  }
}
