import { existsSync } from 'fs';
import { relative, dirname, join } from 'path';
import { ClassInfo, FactoryInfo, ValueInfo } from '../../domain/types';
import { TsMorphTypeParser } from '../parser/TsMorphTypeParser';
import { TsConfigPathsResolver } from '../../utils/tsConfigPathsResolver';
import { ErrorFactory } from '../../errors/errorFactory';

/**
 * Produces the .gen.d.ts type declaration file for type-safe container resolution.
 */
export class TypeDeclarationPrinter {
  static print(
    classes: ClassInfo[],
    outputPath: string,
    parser: TsMorphTypeParser,
    pathsResolver?: TsConfigPathsResolver,
    factories?: FactoryInfo[],
    values?: ValueInfo[]
  ): string {
    this.checkNameCollisions(classes);

    const interfaceClasses = classes.filter((c) => c.interfaceName);
    const abstractClasses = classes.filter((c) => c.abstractClassName);
    const directClasses = classes.filter(
      (c) => !c.interfaceName && !c.abstractClassName
    );

    const hasAny =
      interfaceClasses.length > 0 ||
      abstractClasses.length > 0 ||
      directClasses.length > 0 ||
      (factories && factories.length > 0) ||
      (values && values.length > 0);

    if (!hasAny) {
      return `/**
 * This file is auto-generated by ioc-arise.
 * Do not modify this file manually.
 */

export interface ContainerRegistry {}
`;
    }

    const outputDir = dirname(outputPath);
    const imports = this.buildTypeImports(
      interfaceClasses,
      abstractClasses,
      directClasses,
      outputDir,
      parser,
      pathsResolver,
      factories,
      values
    );

    const entries: string[] = [];

    interfaceClasses.forEach((cls) => {
      entries.push(`  '${cls.interfaceName}': ${cls.interfaceName};`);
    });
    abstractClasses.forEach((cls) => {
      entries.push(`  '${cls.abstractClassName}': ${cls.name};`);
    });
    directClasses.forEach((cls) => {
      entries.push(`  '${cls.name}': ${cls.name};`);
    });

    factories?.forEach((f) => {
      if (f.instanceFactoryFor) {
        entries.push(`  '${f.instanceFactoryFor}': ${f.instanceFactoryFor};`);
      } else {
        const token = f.token ?? f.name;
        entries.push(`  '${token}': ReturnType<typeof ${f.name}>;`);
      }
    });

    values?.forEach((v) => {
      const token = v.token ?? v.interfaceName ?? v.name;
      const type = v.interfaceName ?? `typeof ${v.name}`;
      entries.push(`  '${token}': ${type};`);
    });

    return `/**
 * This file is auto-generated by ioc-arise.
 * Do not modify this file manually.
 *
 * This file provides type-safe resolution for string-based tokens.
 */
${imports}

export interface ContainerRegistry {
${entries.join('\n')}
}
`;
  }

  private static buildTypeImports(
    interfaceClasses: ClassInfo[],
    abstractClasses: ClassInfo[],
    directClasses: ClassInfo[],
    outputDir: string,
    parser: TsMorphTypeParser,
    pathsResolver?: TsConfigPathsResolver,
    factories?: FactoryInfo[],
    values?: ValueInfo[]
  ): string {
    const lines: string[] = [];

    // Interface classes: import the interface type (not the class)
    const interfaceLocations = this.findInterfaceLocations(
      interfaceClasses,
      outputDir,
      parser,
      pathsResolver
    );

    interfaceClasses.forEach((cls) => {
      if (!cls.interfaceName) return;
      const path = interfaceLocations.get(cls.interfaceName);
      if (path) {
        lines.push(`import type { ${cls.interfaceName} } from '${path}';`);
      }
    });

    // Abstract-class implementations: import the concrete class
    abstractClasses.forEach((cls) => {
      const path = this.fileToRelPath(cls.filePath, outputDir);
      lines.push(`import type { ${cls.name} } from '${path}';`);
    });

    // Direct classes: import the class type
    directClasses.forEach((cls) => {
      const path = this.fileToRelPath(cls.filePath, outputDir);
      lines.push(`import type { ${cls.name} } from '${path}';`);
    });

    // Factories
    factories?.forEach((f) => {
      if (f.instanceFactoryFor) {
        const path = this.findInterfaceInFile(
          f.filePath,
          f.instanceFactoryFor,
          outputDir,
          parser,
          pathsResolver
        );
        if (path) {
          lines.push(`import type { ${f.instanceFactoryFor} } from '${path}';`);
        }
      } else {
        const path = this.fileToRelPath(f.filePath, outputDir);
        lines.push(`import { ${f.name} } from '${path}';`);
      }
    });

    // Values: import interface type
    values?.forEach((v) => {
      if (!v.interfaceName) return;
      const path = this.findInterfaceInFile(
        v.filePath,
        v.interfaceName,
        outputDir,
        parser,
        pathsResolver
      );
      if (path) {
        lines.push(`import type { ${v.interfaceName} } from '${path}';`);
      }
    });

    return lines.join('\n');
  }

  private static findInterfaceLocations(
    classes: ClassInfo[],
    outputDir: string,
    parser: TsMorphTypeParser,
    pathsResolver?: TsConfigPathsResolver
  ): Map<string, string> {
    const result = new Map<string, string>();

    for (const cls of classes) {
      if (!cls.interfaceName || result.has(cls.interfaceName)) continue;

      const importMappings = parser.getImportMappingsForFile(cls.filePath);
      const importedFrom = importMappings.get(cls.interfaceName);
      if (!importedFrom) continue;

      const resolved = pathsResolver?.resolveImportToAbsolute(importedFrom)
        ?? require('path').resolve(dirname(cls.filePath), importedFrom);

      const relPath = this.fileToRelPath(resolved, outputDir);
      result.set(cls.interfaceName, relPath);
    }

    return result;
  }

  private static findInterfaceInFile(
    sourceFilePath: string,
    interfaceName: string,
    outputDir: string,
    parser: TsMorphTypeParser,
    pathsResolver?: TsConfigPathsResolver
  ): string | null {
    const importMappings = parser.getImportMappingsForFile(sourceFilePath);
    const importedFrom = importMappings.get(interfaceName);

    if (importedFrom) {
      const resolved =
        pathsResolver?.resolveImportToAbsolute(importedFrom) ??
        join(dirname(sourceFilePath), importedFrom);
      const normalized = resolved.endsWith('.ts')
        ? resolved
        : `${resolved}.ts`;
      if (existsSync(normalized)) {
        return this.fileToRelPath(normalized, outputDir);
      }
    }

    // Fallback: look for {InterfaceName}.ts in same directory
    const candidate = join(dirname(sourceFilePath), `${interfaceName}.ts`);
    if (existsSync(candidate)) {
      return this.fileToRelPath(candidate, outputDir);
    }

    return null;
  }

  private static fileToRelPath(filePath: string, outputDir: string): string {
    let rel = relative(outputDir, filePath).replace(/\.ts$/, '');
    if (!rel.startsWith('.')) rel = `./${rel}`;
    return rel.replace(/\\/g, '/');
  }

  private static checkNameCollisions(classes: ClassInfo[]): void {
    const seen = new Map<string, ClassInfo[]>();
    for (const cls of classes) {
      const bucket = seen.get(cls.name) ?? [];
      bucket.push(cls);
      seen.set(cls.name, bucket);
    }
    for (const [name, bucket] of seen) {
      if (bucket.length > 1) {
        throw ErrorFactory.classNameCollision(
          name,
          bucket.map((c) => c.filePath)
        );
      }
    }
  }
}
